# ------------------------------------------------------------
# Helper: turns 1 -> 1st, 2 -> 2nd, 3 -> 3rd, 4 -> 4th ...
# ------------------------------------------------------------
def ordinal(n):
    if 10 <= n % 100 <= 20:          # 11th, 12th, 13th ... 20th
        suffix = "th"
    else:
        suffix = {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suffix}"


# ------------------------------------------------------------
# INPUT
# ------------------------------------------------------------
smallest = int(input("Enter the 1st number: "))
numbers = [smallest]

for i in range(7):
    num = int(input(f"Enter the {ordinal(i + 2)} number: "))
    numbers.append(num)
    if num < smallest:
        smallest = num


# ------------------------------------------------------------
# CALCULATIONS
# ------------------------------------------------------------
largest = max(numbers)
average = sum(numbers) / len(numbers)
total = sum(numbers)

even_count = 0
odd_count = 0

for n in numbers:
    if n % 2 == 0:
        even_count += 1
    else:
        odd_count += 1

highest_count = max(numbers.count(n) for n in numbers)

if highest_count == 1:
    mode_text = "--"
else:
    modes = sorted(set(n for n in numbers if numbers.count(n) == highest_count))
    mode_text = ", ".join(str(m) for m in modes)


# ------------------------------------------------------------
# RESULTS TABLE
# ------------------------------------------------------------
rows = [
    ("Largest:", largest),
    ("Smallest:", smallest),
    ("Average:", average),
    ("Most Repeated Number:", mode_text),
    ("Sum of these digits are:", total),
    ("Total even numbers in these digits:", even_count),
    ("Odd numbers spotted in these digits:", odd_count),
]

# Column widths are measured from the data, so the table always fits
label_width = max(len(label) for label, value in rows)
value_width = max(10, max(len(str(value)) for label, value in rows))

border = "+" + "-" * (label_width + 2) + "+" + "-" * (value_width + 2) + "+"
table_width = len(border)
